import streamlit as st
import pandas as pd
import joblib

model = joblib.load('breast_cancer_model.pkl')

st.title('Breast Cancer Prediction')

st.write('Введите параметры опухоли')

mean_radius = st.number_input('Mean Radius', value=14.0)
mean_texture = st.number_input('Mean Texture', value=20.0)
mean_perimeter = st.number_input('Mean Perimeter', value=90.0)
mean_area = st.number_input('Mean Area', value=600.0)
mean_smoothness = st.number_input('Mean Smoothness', value=0.1)
input_data = pd.DataFrame({
    'mean radius': [mean_radius],
    'mean texture': [mean_texture],
    'mean perimeter': [mean_perimeter],
    'mean area': [mean_area],
    'mean smoothness': [mean_smoothness],

    'mean compactness': [0.1],
    'mean concavity': [0.1],
    'mean concave points': [0.05],
    'mean symmetry': [0.2],
    'mean fractal dimension': [0.06],

    'radius error': [0.5],
    'texture error': [1.0],
    'perimeter error': [3.0],
    'area error': [40.0],
    'smoothness error': [0.005],

    'compactness error': [0.02],
    'concavity error': [0.03],
    'concave points error': [0.01],
    'symmetry error': [0.02],
    'fractal dimension error': [0.003],

    'worst radius': [16.0],
    'worst texture': [25.0],
    'worst perimeter': [110.0],
    'worst area': [800.0],
    'worst smoothness': [0.15],

    'worst compactness': [0.25],
    'worst concavity': [0.3],
    'worst concave points': [0.12],
    'worst symmetry': [0.3],
    'worst fractal dimension': [0.08]
})
if st.button('Predict'):

    prediction = model.predict(input_data)

    if prediction[0] == 1:
        st.success('Опухоль доброкачественная')
    else:
        st.error('Опухоль злокачественная')

    st.write(prediction)
