# ===== ПРЕОБРАЗОВАНИЕ ОТВЕТОВ =====
def map_choice(choice):
    return {
        "Безопасно": 1,
        "Нормально": 0,
        "Подозрительно": -1
    }[choice]


def safe_input(label, options):
    return map_choice(st.selectbox(label, options))


